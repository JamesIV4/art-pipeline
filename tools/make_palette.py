"""Origin: S:/Repos/trick-or-treat/art/tools/make_palette.py (imported 2026-10-25).
Changed: game paths come from tools/pipeline_paths.py (ART_GAME_ROOT / art/pipeline.json); logic unchanged. C++ header namespace is the cpp_namespace setting; native_header_dir null skips the header.

Builds the shared palette textures from the game's palette spec (default art/palette/palette.json).

Outputs (in palette_out, default game/assets/palette/):
  palette.png       albedo, 256x256, 16x16 cells
  palette_emit.png  glow colour in RGB, flicker amount in A (black for non-glow cells)
  palette_cells.json  name -> {col,row,u,v} used by the Blender kit and the C++ mesh builder
  <native_header_dir>/palette_cells.gen.h  the same table as a C++ header (optional)
Run: python <pipeline>/tools/make_palette.py   (from the game root, or set ART_GAME_ROOT)
"""
import json
import struct
import sys
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pipeline_paths as P  # noqa: E402
SRC = P.path("palette_spec")
OUT = P.path("palette_out")
_HDR_DIR = P.path("native_header_dir")
HEADER = _HDR_DIR / "palette_cells.gen.h" if _HDR_DIR else None
NS = P.setting("cpp_namespace")


def write_png(path, w, h, rgba_rows):
    raw = b"".join(b"\x00" + bytes(row) for row in rgba_rows)

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9))
    png += chunk(b"IEND", b"")
    path.write_bytes(png)


def hex_rgb(h):
    h = h.lstrip("#")
    return [int(h[i:i + 2], 16) for i in (0, 2, 4)]


def main():
    spec = json.loads(SRC.read_text())
    cell, grid = spec["cell_px"], spec["grid"]
    size = cell * grid
    albedo = [[0] * (size * 4) for _ in range(size)]
    emit = [[0] * (size * 4) for _ in range(size)]
    cells = {}
    for r, row in enumerate(spec["rows"]):
        for c, entry in enumerate(row):
            parts = entry.split(":")
            name, rgb = parts[0], hex_rgb(parts[1])
            flicker = float(parts[2]) if len(parts) > 2 else None
            if name in cells:
                raise SystemExit(f"duplicate palette name {name}")
            cells[name] = {"col": c, "row": r, "u": (c + 0.5) / grid, "v": (r + 0.5) / grid,
                           "glow": flicker is not None}
            for y in range(r * cell, (r + 1) * cell):
                for x in range(c * cell, (c + 1) * cell):
                    albedo[y][x * 4:x * 4 + 4] = rgb + [255]
                    if flicker is not None:
                        emit[y][x * 4:x * 4 + 4] = rgb + [int(round(flicker * 255))]
    # unused cells: mid grey so mistakes are visible but not garish
    for y in range(size):
        for x in range(size):
            if albedo[y][x * 4 + 3] == 0:
                albedo[y][x * 4:x * 4 + 4] = [255, 0, 255, 255]
    OUT.mkdir(parents=True, exist_ok=True)
    write_png(OUT / "palette.png", size, size, albedo)
    write_png(OUT / "palette_emit.png", size, size, emit)
    (OUT / "palette_cells.json").write_text(json.dumps(cells, indent=1))

    lines = ["// Generated by art/tools/make_palette.py. Do not edit.", "#pragma once", "",
             f"namespace {NS}::pal {{", f"constexpr int GRID = {grid};", ""]
    for name, info in cells.items():
        lines.append(f"constexpr int {name.upper()} = {info['row'] * grid + info['col']};")
    rgb = ["0xff00ff"] * (grid * grid)
    for r, row in enumerate(spec["rows"]):
        for c, entry in enumerate(row):
            rgb[r * grid + c] = "0x" + entry.split(":")[1].lstrip("#")
    lines += ["", f"// sRGB colour of every cell (0xRRGGBB).", f"constexpr unsigned RGB[{grid * grid}] = {{"]
    for i in range(0, len(rgb), 16):
        lines.append("\t" + ", ".join(rgb[i:i + 16]) + ",")
    lines += ["};", "", f"}} // namespace {NS}::pal", ""]
    if HEADER is not None:
        HEADER.parent.mkdir(parents=True, exist_ok=True)
        HEADER.write_text("\n".join(lines))
    print(f"{len(cells)} palette cells -> {OUT}")


if __name__ == "__main__":
    main()
